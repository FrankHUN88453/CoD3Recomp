"""Recompiles the multiplayer executable, codmp_xenonf.xex, into
CoD3RecompLib/ppc_mp, the way recompile_level.ps1 does a level:

  1. the register save/restore helpers from CoD3Scan
  2. the jump tables from XenonAnalyse
  3. XenonRecomp, again and again, mending the functions the analyser cut
     short: CoD3Scan --fixfuncs from the recompiler's report, then
     level_functions.py from the generated code, until nothing changes.
     What both find is kept in config/CoD3MP_functions.toml.

    python scripts/recompile_mp.py <tools build dir> <CoD3Scan path>

The XEX is read from CoD3RecompLib/private/codmp_xenonf.xex.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "CoD3RecompLib"
NAME = "CoD3MP"
XEX = LIB / "private" / "codmp_xenonf.xex"
CONFIG = LIB / "config" / f"{NAME}.toml"
SWITCHES = LIB / "config" / f"{NAME}_switch_tables.toml"
KEPT = LIB / "config" / f"{NAME}_functions.toml"
OUT = LIB / "ppc_mp"
LOG = ROOT / "recomp_mp.log"
ENTRY = re.compile(r"^\s*\{ address = (0x[0-9A-F]+), size = (0x[0-9A-F]+) \},.*$")

# The C runtime's longjmp and setjmp: matched instruction for instruction
# against the single player executable's (0x8234EEC0 and 0x82351CC0 there).
LONGJMP = 0x8231E400
SETJMP = 0x82322010


def exe(path):
    p = pathlib.Path(path)
    if sys.platform == "win32" and p.suffix == "":
        p = p.with_suffix(".exe")
    return str(p)


def run(args, **kw):
    return subprocess.run(args, capture_output=True, text=True, errors="replace", **kw)


def read_entries(text):
    found = {}
    for line in text.splitlines():
        m = ENTRY.match(line)
        if m:
            found[int(m.group(1), 16)] = line.strip()
    return found


def write_config(helpers, functions):
    lines = [
        "# Call of Duty 3 (Xbox 360) - the multiplayer executable, codmp_xenonf.xex.",
        "# Generated by scripts/recompile_mp.py; edit config/CoD3MP_functions.toml instead.",
        "",
        "[main]",
        'file_path = "../private/codmp_xenonf.xex"',
        'out_directory_path = "../ppc_mp"',
        f'switch_table_file_path = "{SWITCHES.name}"',
        "",
        "skip_lr = false", "skip_msr = false", "ctr_as_local = false", "xer_as_local = false",
        "reserved_as_local = false", "cr_as_local = false", "non_argument_as_local = false",
        "non_volatile_as_local = false",
        "",
    ] + helpers + [
        f"longjmp_address = 0x{LONGJMP:08X}",
        f"setjmp_address  = 0x{SETJMP:08X}",
        "",
        "invalid_instructions = [",
        "    { data = 0x00000000, size = 4 }, # padding",
        "]",
    ]
    if functions:
        lines += ["", "functions = ["] + [functions[a] for a in sorted(functions)] + ["]"]
    CONFIG.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


def recompile(recomp, context):
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*"):
        if f.is_file():
            f.unlink()
    r = run([recomp, str(CONFIG), str(context)], cwd=str(LIB / "config"))
    LOG.write_text(r.stdout + r.stderr, encoding="utf-8")
    if r.returncode != 0:
        sys.exit(f"XenonRecomp failed (exit {r.returncode}); see {LOG}")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tools = pathlib.Path(sys.argv[1]).resolve()
    scan = exe(pathlib.Path(sys.argv[2]).resolve())
    recomp = exe(tools / "XenonRecomp" / "XenonRecomp")
    analyse = exe(tools / "XenonAnalyse" / "XenonAnalyse")
    context = ROOT / "tools" / "XenonRecomp" / "XenonUtils" / "ppc_context.h"
    if not XEX.exists():
        sys.exit(f"{XEX} is missing: copy codmp_xenonf.xex there from the installed game")

    text = run([scan, str(XEX)]).stdout
    helpers = re.findall(r"^((?:rest|save)(?:gprlr|fpr|vmx)_(?:14|64)_address) = (0x[0-9A-F]+)", text, re.M)
    if len(helpers) < 8:
        sys.exit("the save/restore helpers were not all found:\n" + text)
    helpers = [f"{k} = {v}" for k, v in helpers]

    print("==> jump tables")
    run([analyse, str(XEX), str(SWITCHES)])
    tables = len(re.findall(r"^\[\[switch\]\]", SWITCHES.read_text(), re.M))
    print(f"    {tables} switch tables")

    kept = read_entries(KEPT.read_text()) if KEPT.exists() else {}
    functions = dict(kept)
    print("==> recompiling")
    for p in range(1, 7):
        write_config(helpers, functions)
        recompile(recomp, context)
        if "is trying to jump outside function" not in LOG.read_text(errors="replace"):
            break
        fixed = read_entries(run([scan, str(XEX), "--fixfuncs", str(LOG)]).stdout)
        if not fixed:
            sys.exit("functions to fix were reported but CoD3Scan found none")
        functions.update(fixed)
        functions.update(kept)
        print(f"    pass {p}: {len(fixed)} function boundaries fixed")
    for p in range(1, 9):
        report = run([sys.executable, str(ROOT / "scripts" / "level_functions.py"), NAME]).stdout.strip()
        print("    " + report)
        if ": 0 function extents" in report:
            break
        kept = read_entries(KEPT.read_text())
        functions.update(kept)
        write_config(helpers, functions)
        recompile(recomp, context)

    sources = list(OUT.glob("ppc_recomp.*.cpp"))
    count = sum(t.count("PPC_FUNC_IMPL(") for t in (s.read_text(errors="replace") for s in sources))
    errors = sum(len(re.findall(r"// ERROR [0-9A-F]+", s.read_text(errors="replace"))) for s in sources)
    unknown = LOG.read_text(errors="replace").count("Unrecognized instruction")
    print(f"    {count} functions in {len(sources)} files, {unknown} unrecognized instructions, {errors} branches out of their function")


if __name__ == "__main__":
    main()
